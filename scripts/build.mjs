import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {validateSettings} from '../netlify/lib/settings.mjs';

const settings = JSON.parse(await readFile(new URL('../site.config.json', import.meta.url), 'utf8'));
validateSettings(settings);
const publicSettings = {targetUrl: settings.targetUrl, countdownSeconds: settings.countdownSeconds};
await writeFile(new URL('../dist/site-config.js', import.meta.url),
  `// Generated by npm run build from site.config.json.\nwindow.NAIWA_CONFIG = Object.freeze(${JSON.stringify(publicSettings, null, 2)});\n`);
console.log(`Prepared static site: ${fileURLToPath(new URL('../dist/', import.meta.url))}`);
